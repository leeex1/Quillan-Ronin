#pragma once
#include <string>
#include <vector>
#include <iostream>      // For logging
#include "EventTypes.h"  // Include the actual definition

// Forward declaration
class AudioEffect;

/**
 * @class MidiTrack
 * @brief Represents a track in the DAW that holds MIDI data and instrument settings.
 *
 * MidiTracks contain MIDI events and can have effects applied to their audio output
 * (conceptually, after MIDI data is synthesized into audio).
 */
class MidiTrack {
public:
    /**
     * @brief Constructor for MidiTrack.
     * @param name The initial name of the track.
     */
    MidiTrack(const std::string& name);
    /**
     * @brief Destructor for MidiTrack.
     * Manages the cleanup of associated effects.
     */
    ~MidiTrack();

    // effects_ holds owning raw pointers: copying would double-delete them.
    MidiTrack(const MidiTrack&) = delete;
    MidiTrack& operator=(const MidiTrack&) = delete;
    MidiTrack(MidiTrack&&) = default;
    MidiTrack& operator=(MidiTrack&&) = default;

    /**
     * @brief Sets the name of the MIDI track.
     * @param name The new name for the track.
     */
    void setName(const std::string& name);
    /**
     * @brief Gets the current name of the MIDI track.
     * @return The name of the track.
     */
    std::string getName() const;

    /**
     * @brief Adds a MIDI event to the track.
     * @param event The MidiEvent to add.
     */
    void addEvent(const MidiEvent& event); // Implementation in .cpp
    /**
     * @brief Gets all MIDI events on this track.
     * @return A constant reference to the vector of MidiEvents.
     */
    const std::vector<MidiEvent>& getEvents() const;

    // --- Audio Effects (applied to the synthesized output of the MIDI track) ---
    /**
     * @brief Adds an audio effect to the track's effect chain.
     * The track takes ownership of the effect pointer.
     * @param effect Pointer to an AudioEffect object.
     */
    void addEffect(AudioEffect* effect);

    /**
     * @brief Retrieves the list of audio effects applied to this track.
     * These effects would process the audio generated by the MIDI instrument.
     * @return A constant reference to the vector of AudioEffect pointers.
     */
    const std::vector<AudioEffect*>& getEffects() const;

    // --- Track Properties ---
    std::string instrumentName = "Default Instrument"; ///< Name of the instrument assigned to this track.
    int midiChannel = 1;                            ///< MIDI channel for this track (1-16).
    float volume = 1.0f;                            ///< Volume of the track.
    float pan = 0.0f;                               ///< Panning of the track.
    bool isMuted = false;                           ///< Mute state.
    bool isSoloed = false;                          ///< Solo state.

private:
    std::string trackName;
    std::vector<MidiEvent> midiEvents;      ///< Stores MIDI events for this track.
    std::vector<AudioEffect*> effects_;     ///< Chain of audio effects for this track's output.

    /**
     * @brief Logs a message specific to MidiTrack operations.
     * @param message The message string to log.
     */
    void log(const std::string& message) const {
        std::cout << "[MidiTrack: " << trackName << " LOG]: " << message << std::endl;
    }

    /**
     * @brief Logs an error message specific to MidiTrack operations.
     * @param message The error message string to log.
     */
    void logError(const std::string& message) const {
        std::cerr << "[MidiTrack: " << trackName << " ERROR]: " << message << std::endl;
    }
};
